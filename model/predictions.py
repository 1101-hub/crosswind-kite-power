"""
Generate the PRE-REGISTERED PREDICTIONS document.

Why this file exists
--------------------
Every prediction below is computed from the model BEFORE any measurement is
taken. The numbers are written to a dated file which then does not get edited.
When the flight data comes in, it is compared against this file.

That is the whole point. A model that is tuned after seeing the data can fit
anything; a model that commits to numbers in advance can be WRONG, and being
capable of being wrong is what makes it science rather than curve-fitting.

Print this, date it, and put it on the poster. Judges recognise
pre-registration and almost no school project does it.

Usage:
    python predictions.py            # uses the patang config
    python predictions.py trainer    # uses the 1.5 m^2 trainer foil
"""

import sys
import datetime
import numpy as np

import kite as K
import optimize as O


# ---------------------------------------------------------------------------
# Systems under test.  EDIT THESE to match your actual hardware.
# ---------------------------------------------------------------------------

PATANG = {
    'name': 'Indian festival patang (paper/bamboo diamond)',
    'area': 0.12,              # m^2  <-- MEASURE YOURS: area of the diamond
    'cl': 0.70,                # flat bowed plate, estimated
    'cd': 0.25,                # low aspect ratio -> heavy induced drag
    'cl_depowered': 0.15,
    'mass': 0.012,             # kg   <-- WEIGH YOURS
    'tether_length': 50.0,     # m    <-- MEASURE YOUR LINE
    'tether_diameter': 0.0005,  # m   plain cotton/polyester, NEVER manja
    'aspect_ratio': 1.6,
    'zeta_turn': 1.0,
    'tension_limit': 60.0,
}

TRAINER = {
    'name': 'Trainer foil kite 1.5 m^2',
    'area': 1.5, 'cl': 0.90, 'cd': 0.20, 'cl_depowered': 0.15,
    'mass': 0.9, 'tether_length': 50.0, 'tether_diameter': 0.0015,
    'aspect_ratio': 4.0, 'zeta_turn': 1.0, 'tension_limit': 600.0,
}

WIND_SPEEDS = [3.0, 4.0, 5.0, 6.0, 7.0]


# ---------------------------------------------------------------------------

def glide_ratio(cfg):
    return K.effective_glide_ratio(cfg['cl'], cfg['cd'], cfg['tether_length'],
                                   cfg['tether_diameter'], cfg['area'])


def gravity_number(cfg, v):
    return cfg['mass'] * K.G / (0.5 * K.RHO * v ** 2 * cfg['area'] * cfg['cl'])


def build(cfg):
    lines = []
    w = lines.append
    E = glide_ratio(cfg)

    w("=" * 74)
    w("PRE-REGISTERED PREDICTIONS")
    w(cfg['name'])
    w("Generated: " + datetime.datetime.now().strftime("%Y-%m-%d %H:%M"))
    w("=" * 74)
    w("")
    w("These numbers were computed BEFORE any measurement was taken.")
    w("Do not edit this file after flying. Compare against it.")
    w("")
    w("SYSTEM")
    w("  area          %.3f m^2      mass           %.3f kg" % (cfg['area'], cfg['mass']))
    w("  C_L           %.2f           C_D (kite)     %.2f" % (cfg['cl'], cfg['cd']))
    w("  tether        %.0f m         diameter       %.1f mm"
      % (cfg['tether_length'], cfg['tether_diameter'] * 1000))
    w("  E_eff = C_L / (C_D + C_Dt*d*L/(4A))       = %.2f" % E)
    w("")

    # ---- 1 --------------------------------------------------------------
    w("-" * 74)
    w("P1  GLIDE RATIO FROM A STATIC KITE")
    w("-" * 74)
    w("  Park the kite at the top of the window, directly downwind, and hold")
    w("  it still. Measure line tension T and elevation angle beta.")
    w("")
    w("      E = (T sin(beta) + W) / (T cos(beta))          W = m g = %.3f N"
      % (cfg['mass'] * K.G))
    w("")
    w("  PREDICTION: E comes out the same at every wind speed, within scatter,")
    w("              and equals %.2f +/- 0.3" % E)
    w("  FALSIFIED IF: E drifts systematically with wind speed. That would mean")
    w("              Reynolds effects or canopy deformation matter at this scale.")
    w("")
    w("  Expected static readings:")
    w("    %-8s %-14s %-14s %s" % ("wind", "tension", "in grams", "elevation"))
    for v in WIND_SPEEDS:
        T, b = K.static_tension_and_angle(v, cfg['area'], cfg['cl'],
                                          cfg['cd'], cfg['mass'])
        w("    %-8.1f %-14.2f %-14.0f %.0f deg" % (v, T, T / K.G * 1000, b))
    w("")

    # ---- 2 --------------------------------------------------------------
    w("-" * 74)
    w("P2  CROSSWIND TENSION AMPLIFICATION      <-- the headline")
    w("-" * 74)
    w("  Fly figure-eights. Tension must jump by roughly E^2 cos^2(theta),")
    w("  reduced by the reel-out term. ZERO FITTED PARAMETERS: E comes from P1.")
    w("")
    w("    %-8s %-12s %-12s %s" % ("wind", "static (N)", "crosswind (N)", "amplification"))
    for v in WIND_SPEEDS:
        Ts, _ = K.static_tension_and_angle(v, cfg['area'], cfg['cl'],
                                           cfg['cd'], cfg['mass'])
        try:
            p, fo, fi, _ = O.optimize_lissajous(v, cfg)
            r = K.cycle_power(v, cfg, p, fo, fi, 65.0, 30.0)
            Tc = r['tension_mean']
            w("    %-8.1f %-12.2f %-12.2f x%.1f" % (v, Ts, Tc, Tc / Ts))
        except Exception:
            w("    %-8.1f %-12.2f %-12s --" % (v, Ts, "no flight"))
    w("")
    w("  FALSIFIED IF: the jump is absent, or off by more than ~2x.")
    w("")

    # ---- 3 --------------------------------------------------------------
    w("-" * 74)
    w("P3  TENSION WAVEFORM SHAPE WITHIN ONE LOOP")
    w("-" * 74)
    w("  Not just the average -- the SHAPE. Within a single figure-eight,")
    w("      T(t) proportional to cos^2(theta(t)),   cos(theta)=cos(beta)cos(phi)")
    w("  so tension PEAKS at the centre of the eight (kite lowest and most")
    w("  directly downwind) and DIPS at the two outer edges.")
    w("")
    w("  PREDICTION: two tension peaks per full figure-eight, since the kite")
    w("              crosses the powered centre twice per loop.")
    w("  FALSIFIED IF: one peak per loop, or peaks at the edges instead.")
    w("")

    # ---- 4 --------------------------------------------------------------
    w("-" * 74)
    w("P4  FRACTION OF THE LOYD CEILING ACHIEVED")
    w("-" * 74)
    w("      P_Loyd = (2/27) rho A v^3 C_L E^2")
    w("  Published full-scale systems reach 10-30 percent of this.")
    w("")
    w("    %-8s %-14s %-14s %s" % ("wind", "Loyd (W)", "model (W)", "fraction"))
    for v in WIND_SPEEDS:
        loyd = K.loyd_limit(v, cfg['area'], cfg['cl'], E)
        try:
            _, _, _, pw = O.optimize_lissajous(v, cfg)
            w("    %-8.1f %-14.2f %-14.2f %.0f%%" % (v, loyd, pw, 100 * pw / loyd))
        except Exception:
            w("    %-8.1f %-14.2f %-14s --" % (v, loyd, "no flight"))
    w("")
    w("  PREDICTION: measured power lands BELOW the model, because the model")
    w("              has no turning losses, no control losses and no")
    w("              unsteady effects. Expect zeta_turn in the range 0.5-0.8.")
    w("")

    # ---- 5 --------------------------------------------------------------
    w("-" * 74)
    w("P5  AN OPTIMAL TETHER LENGTH EXISTS")
    w("-" * 74)
    w("  Longer tether reaches faster wind but adds drag. Trade-off gives")
    w("      L_opt = 3 alpha C_D,kite / (kappa (2 - 3 alpha)),  kappa=C_Dt d/(4A)")
    w("")
    for alpha in (0.10, 0.14, 0.20):
        L = K.optimal_tether_length(cfg['cd'], cfg['tether_diameter'],
                                    cfg['area'], shear_exponent=alpha)
        w("    wind shear exponent alpha=%.2f  ->  L_opt = %.0f m" % (alpha, L))
    w("")
    w("  PREDICTION: fly at 3 tether lengths spanning L_opt. Power per unit")
    w("              area peaks in the middle, not at the longest line.")
    w("  FALSIFIED IF: power rises monotonically with length.")
    w("")

    # ---- 6 --------------------------------------------------------------
    w("-" * 74)
    w("P6  MINIMUM WIND SPEED FOR SUSTAINED CROSSWIND FLIGHT")
    w("-" * 74)
    w("  Flight speed solves  v_a^2 - b v_a + c = 0  with")
    w("      b = E (v_w cos(theta) - v_r)     c = m g climb / (0.5 rho A C_D)")
    w("  If the DISCRIMINANT b^2 - 4c < 0 there is no real solution: the kite")
    w("  physically cannot complete the climb and falls out of the sky.")
    w("")
    w("  PREDICTION: sustained figure-eights become impossible below")
    w("              v_min = %.2f m/s" % K.minimum_wind_for_crosswind(cfg))
    w("  This is the sharpest prediction here -- an algebraic condition on a")
    w("  discriminant, predicting something you can watch happen in a field.")
    w("  FALSIFIED IF: the kite flies loops well below that, or fails well above.")
    w("")
    w("  Gravity number G = mg/(0.5 rho v^2 A C_L):")
    for v in WIND_SPEEDS:
        w("    v=%.1f m/s   G=%.3f" % (v, gravity_number(cfg, v)))
    w("")

    # ---- 7 --------------------------------------------------------------
    w("-" * 74)
    w("P7  TETHER DRAG LUMPS AS C_Dt d L / (4 A)")
    w("-" * 74)
    w("  The standard formula every AWE paper uses. Test it directly: measure")
    w("  E from the static test (P1) at several tether lengths.")
    w("")
    w("    %-14s %-14s %s" % ("tether L (m)", "predicted E", "tether share of drag"))
    for L in (20.0, 40.0, 60.0, 80.0, 100.0):
        cd_t = K.effective_drag_coefficient(cfg['cd'], L, cfg['tether_diameter'],
                                            cfg['area'])
        w("    %-14.0f %-14.2f %.0f%%"
          % (L, cfg['cl'] / cd_t, 100 * (cd_t - cfg['cd']) / cd_t))
    w("")
    w("  PREDICTION: E falls with tether length exactly as above.")
    w("  FALSIFIED IF: E is flat with length (formula overstates tether drag)")
    w("              or falls faster (formula understates it).")
    w("")
    w("=" * 74)
    w("END OF PRE-REGISTRATION.  Do not edit below this line after flying.")
    w("=" * 74)

    return "\n".join(lines)


if __name__ == '__main__':
    cfg = TRAINER if len(sys.argv) > 1 and sys.argv[1] == 'trainer' else PATANG
    text = build(cfg)
    print(text)
    stamp = datetime.date.today().isoformat()
    fname = "../predictions_%s_%s.txt" % (
        'trainer' if cfg is TRAINER else 'patang', stamp)
    with open(fname, 'w') as f:
        f.write(text)
    print("\n[written to %s]" % fname)
